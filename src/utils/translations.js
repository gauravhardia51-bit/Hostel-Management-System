    RENT: { en: "Room Rent", hi: "कमरा किराया" },
    ROOM_RENT: { en: "Room Rent", hi: "कमरा किराया" },
    ELECTRICITY: { en: "Electricity Bill", hi: "बिजली बिल" },
    ELECTRICITY_BILL: { en: "Electricity Bill", hi: "बिजली बिल" },
